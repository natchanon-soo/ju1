// Calculate Budget
// =========================

organizations.forEach(org => {
    org.budget = org.projects.reduce(
        (sum, project) =>
            sum + project.budget,
        0
    );
});

export const totalBudget = organizations.reduce(
    (sum, org) =>
        sum + org.budget,
    0
);

export const tattoos = organizations.map(org => {
    const percent = (org.budget / totalBudget) * 100;
    return {
        ...org,
        level: "องค์กร",
        budgetText:
            org.budget.toLocaleString("th-TH") + " บาท",
        wp: percent,
        percent: percent.toFixed(2),
        projects: org.projects.map(project => {
            const projectPercent =
                (project.budget / totalBudget) * 100;
            return {
                ...project,
                organization: org.organization,
                img: org.img,
                budgetText: project.budget.toLocaleString("th-TH") + " บาท",
                wp: projectPercent,
                percent: projectPercent.toFixed(2)
            };
        })
    };
});

export const totalBudgetText = totalBudget.toLocaleString("th-TH") + " บาท";
